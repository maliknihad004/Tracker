    CONSTRAINT "CK_CrawlRun_Dates" CHECK ("finished_at" IS NULL OR ("started_at" IS NOT NULL AND "finished_at" >= "started_at")),
    CONSTRAINT "CK_CrawlRun_ProductsFound" CHECK ("products_found" >= 0),
    CONSTRAINT "CK_CrawlRun_Status" CHECK ("status" IN ('Pending','Running','Completed','Failed')),
    CONSTRAINT "FK_CrawlRun_Retailer" FOREIGN KEY (retailer_id) REFERENCES "Retailer" (retailer_id) ON DELETE RESTRICT
