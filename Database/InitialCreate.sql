CREATE TABLE "Category" (
    category_id integer GENERATED BY DEFAULT AS IDENTITY,
    parent_category_id integer,
    slug character varying(150) NOT NULL,
    name_translation_key character varying(200) NOT NULL,
    description_translation_key character varying(200),
    is_active boolean NOT NULL DEFAULT TRUE,
    CONSTRAINT "PK_Category" PRIMARY KEY (category_id),
    CONSTRAINT "CK_Category_DescriptionTranslationKey" CHECK (description_translation_key IS NULL OR length(trim(description_translation_key)) > 0),
    CONSTRAINT "CK_Category_NameTranslationKey" CHECK (length(trim(name_translation_key)) > 0),
    CONSTRAINT "CK_Category_NotOwnParent" CHECK (parent_category_id IS NULL OR parent_category_id <> category_id),
    CONSTRAINT "CK_Category_Slug" CHECK (length(trim(slug)) > 0),
    CONSTRAINT "FK_Category_Category" FOREIGN KEY (parent_category_id) REFERENCES "Category" (category_id) ON DELETE RESTRICT
